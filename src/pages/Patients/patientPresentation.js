export function patientDisplayValue(value, language = 'el') {
  if (value == null || value === '') return value
  return language === 'en' ? (EN[String(value)] || value) : value
}

export function patientCount(count, kind, language = 'el') {
  const n = Number(count) || 0
  if (language === 'en') {
    const labels = {
      activeCase: n === 1 ? 'active' : 'active',
      sample: n === 1 ? 'sample' : 'samples',
      closedCase: n === 1 ? 'closed case' : 'closed cases',
      file: n === 1 ? 'file' : 'files',
      followUp: n === 1 ? 'follow-up' : 'follow-ups',
    }
    return `${n} ${labels[kind] || kind}`
  }
  const labels = {
    activeCase: n === 1 ? 'ενεργή' : 'ενεργές',
    sample: n === 1 ? 'δείγμα' : 'δείγματα',
    closedCase: n === 1 ? 'κλειστός φάκελος' : 'κλειστοί φάκελοι',
    file: n === 1 ? 'αρχείο' : 'αρχεία',
    followUp: n === 1 ? 'επανέλεγχος' : 'επανέλεγχοι',
  }
  return `${n} ${labels[kind] || kind}`
}
